// Writes the ABIs and bytecode of the deployable Ferry contracts to shared/ferryArtifacts.ts.
import { readFileSync, writeFileSync } from "node:fs";

const contracts = {
  FerryEscrow: "artifacts/contracts/ethereum/FerryEscrow.sol/FerryEscrow.json",
  FerryMezo: "artifacts/contracts/mezo/FerryMezo.sol/FerryMezo.json",
  VaaVerifier: "artifacts/contracts/ethereum/VaaVerifier.sol/VaaVerifier.json",
};

let out = "// GENERATED by contracts/scripts/export-abis.ts — do not edit.\n\n";
for (const [name, path] of Object.entries(contracts)) {
  const a = JSON.parse(readFileSync(path, "utf8"));
  const lower = name[0].toLowerCase() + name.slice(1);
  out += `export const ${lower}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n\n`;
  out += `export const ${lower}Bytecode = "${a.bytecode}" as const;\n\n`;
}
writeFileSync("../shared/ferryArtifacts.ts", out);
console.log("wrote shared/ferryArtifacts.ts");
